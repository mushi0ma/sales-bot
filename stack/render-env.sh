#!/usr/bin/env bash
# Build stack/.env (mode 600, never in git) from Secret Manager on the VM, through the VM's service account.
# Run before `docker compose up` and after any secret changes. Prints names only.
set -euo pipefail
stack="$(cd "$(dirname "$0")" && pwd)"
root="$(dirname "$stack")"
source "$root/deploy/gcp.env"
umask 077
tmp="$(mktemp "$stack/.env.XXXXXX")"
trap 'rm -f "$tmp"' EXIT
{
  echo "# GENERATED by stack/render-env.sh from Secret Manager ($GCP_PROJECT). Do not edit, copy out or commit."
  echo "GCP_PROJECT=$GCP_PROJECT"
  echo "PUBLIC_DOMAIN=$PUBLIC_DOMAIN"
} > "$tmp"
missing=()
while read -r name var src; do
  if v="$(gcloud secrets versions access latest --secret="$name" --project="$GCP_PROJECT" </dev/null 2>/dev/null)"; then
    [[ "$v" != *$'\n'* ]] || { echo "secret $name has a newline; refusing" >&2; exit 1; }
    printf '%s=%s\n' "$var" "$v" >> "$tmp"
  else
    [[ "$src" == gen:* ]] && missing+=("$name")
    printf '%s=\n' "$var" >> "$tmp"
  fi
done < <(grep -vE '^\s*(#|$)' "$root/deploy/secrets.map")
unset v
# Keep what bootstrap.py and platform/setup.py wrote (CW_TGU_*, GW_*, HATCHET_*, TWENTY_API_KEY: ids and tokens
# minted inside Chatwoot, Hatchet, Twenty), unless a secret now sets it.
if [[ -f "$stack/.env" ]]; then
  while IFS= read -r line; do
    [[ "$line" =~ ^([A-Z0-9_]+)= ]] || continue
    grep -q "^${BASH_REMATCH[1]}=" "$tmp" || printf '%s\n' "$line" >> "$tmp"
  done < "$stack/.env"
fi
if (( ${#missing[@]} )); then echo "empty required secrets: ${missing[*]} (run deploy/secrets.sh init)" >&2; exit 1; fi
chmod 600 "$tmp"; mv "$tmp" "$stack/.env"; trap - EXIT
echo "wrote $stack/.env (600): $(grep -c '=' "$stack/.env") variables, empty: $(grep -cE '^[A-Z_]+=$' "$stack/.env")"
