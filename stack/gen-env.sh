#!/usr/bin/env bash
# Generate stack/.env with fresh random secrets. Run INSIDE the VM. Never prints secret values.
# Never overwrites an existing .env (rotating ENCRYPTION_KEY would orphan the agents vault); it only
# appends variables that newer stack versions need.
set -euo pipefail
cd "$(dirname "$0")"
s() { openssl rand -hex "${1:-32}"; }
umask 077
if [[ -e .env ]]; then
  # Never rotate existing secrets; only append variables added to the stack later.
  added=0
  [[ -n "$(tail -c1 .env)" ]] && echo >> .env  # a hand-edited .env without a final newline
  grep -q '^TICKETS_API_TOKEN=' .env || { echo "TICKETS_API_TOKEN=$(s 32)" >> .env; added=$((added+1)); }
  echo ".env exists; not rotating. Added $added missing variable(s)."; exit 0
fi
CW_PG=$(s 24); AG_PG=$(s 24); AG_APP=$(s 24)
cat > .env <<EOF
# SENSITIVE — generated by gen-env.sh inside the VM. Do NOT copy out or commit.
# Chatwoot
SECRET_KEY_BASE=$(s 64)
CW_POSTGRES_PASSWORD=$CW_PG
REDIS_PASSWORD=$(s 24)
# agents
AGENTS_POSTGRES_PASSWORD=$AG_PG
AGENTS_APP_DB_PASSWORD=$AG_APP
JWT_SECRET=$(s 32)
MCP_JWT_SECRET=$(s 32)
ENCRYPTION_KEY=$(s 32)
# mock dispatcher (ticket HTTP tools)
TICKETS_API_TOKEN=$(s 32)
EOF
chmod 600 .env
echo "wrote $(pwd)/.env (mode 600), $(grep -c '=' .env) variables"
